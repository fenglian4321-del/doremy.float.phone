import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const kv = new Map(), module = { exports: {} };
const code = ts.transpileModule(readFileSync(new URL('../lib/usage-cost.ts', import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { module, exports: module.exports, require: name => { assert.equal(name, './kv-db'); return { kvGet: key => kv.get(key), kvSet: (key, value) => kv.set(key, value), registerKvMigration() {} }; } });
const api = module.exports;
const rate = { configId: 'synthetic-api', provider: 'Custom', model: 'synthetic-model', currency: 'CNY', input: 10, output: 30, cacheRead: 2, cacheWrite: 20 };
const row = { ...rate, source: 'chat', status: 'completed', usage: { prompt_tokens: 1000, completion_tokens: 100, cached_tokens: 400, cache_creation_tokens: 100 } };
assert.equal(api.estimateUsageCost(row, []), undefined);
api.saveUsageRate(rate); const rates = api.loadUsageRates();
// 500 normal + 400 cache-read + 100 cache-write input, plus 100 output.
assert.ok(Math.abs(api.estimateUsageCost(row, rates).amount - 0.0108) < 1e-12);
assert.equal(api.estimateUsageCost({ ...row, usage: { prompt_tokens: 1000, completion_tokens: 100 } }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, usage: { ...row.usage, cached_tokens: 1001 } }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, usage: { ...row.usage, completion_tokens: undefined } }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, source: 'tool' }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, status: 'pending' }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, configId: 'other-api' }, rates), undefined);
assert.equal(api.estimateUsageCost({ ...row, model: 'other-model' }, rates), undefined);
const flat = { ...rate, cacheRead: 10, cacheWrite: 10 };
assert.equal(api.estimateUsageCost({ ...row, usage: { prompt_tokens: 1000, completion_tokens: 100 } }, [flat]).amount, 0.013);
api.saveUsageRate({ ...rate, input: 0, output: 0, cacheRead: 0, cacheWrite: 0 });
assert.equal(api.estimateUsageCost({ ...row, usage: { prompt_tokens: 0, completion_tokens: 0 } }, api.loadUsageRates()).amount, 0);
for (const invalid of [{ input: -1 }, { output: NaN }, { cacheRead: Infinity }, { cacheWrite: 1000001 }, { currency: 'BTC' }, { model: 'Bearer SECRET' }]) assert.throws(() => api.saveUsageRate({ ...rate, ...invalid }));
const usdRate = { ...rate, configId: 'usd-api', currency: 'USD' };
const sum = api.summarizeUsageCost([row, { ...row, configId: 'usd-api' }, { ...row, usage: undefined }, { ...row, source: 'tool' }], [rate, usdRate]);
assert.equal(sum.priced, 2); assert.equal(sum.unknown, 1); assert.ok(sum.totals.CNY > 0); assert.ok(sum.totals.USD > 0);
api.removeUsageRate(rate); assert.equal(api.loadUsageRates().length, 0);
assert.ok(!JSON.stringify([...kv.values()]).includes('SECRET'));
console.log('Manual cost: no assumed price, unknown/zero distinction, no cache double-count, separate currencies, config/model binding, and invalid rates rejected.');
